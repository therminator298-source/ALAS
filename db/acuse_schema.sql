--  Patrón: RLS abierta a anon (el gate real es el SSO ALAS en la UI), igual
--  que los otros módulos vanilla del ecosistema. La anon key es pública por
--  diseño. NUNCA usar service_role en el cliente.
--
--  Estados canónicos: 'Pendiente' · 'En Reparto' · 'Entregado' · 'Anulado'
